TILES = 12


def paths() -> dict[str, int]:
    request = urllib.request.Request(FILES, headers={"User-Agent": "TweaksForever/1.0"})
    with urllib.request.urlopen(request, timeout=180) as response:
        rows = json.load(response)
    return {path.replace("\\/", "/").lower(): int(id) for id, path in rows.items()}


def sheet(directory: str, prefix: str, floor: int, numbered: bool) -> str:
    """One floor's sheet prefix: the addon appends tile 1..12, with the separator the client uses."""
    return f"Interface\\WorldMap\\{directory}\\{prefix}{floor if numbered else ''}"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="Data/DungeonMapArt.lua")
    args = parser.parse_args()
    shipped = paths()
    lines = [
        "-- Generated by tools/gen_dungeonmaps.py — do not edit.",
        f"-- The client's own dungeon interior sheets for build {BUILD}: a floor is twelve 256 by 256 tiles in four",
        "-- columns and three rows, and the art carries the dungeon's name, its area labels and a skull on every boss",
        "-- room, so the addon draws it as it is. Tile n is `pattern .. separator .. n`.",
        "local _, ns = ...",
        "ns.DungeonMapArt = {",
    ]
    missing, written = [], 0
    for instance, (where, floors, titles) in sorted(INSTANCES.items()):
        directory, prefix = where.split("/")
        rows = []
        for floor in floors:
            numbered = instance != 209
            stem = sheet(directory, prefix, floor, numbered)
            folder = f"interface/worldmap/{directory.lower()}/"
            tiles = [
                folder + f"{prefix.lower()}{floor if numbered else ''}" + ("_" if numbered else "") + str(n)
                for n in range(1, TILES + 1)
            ]
            if not all(f"{tile}.blp" in shipped for tile in tiles):
                missing.append(f"{NAMES[instance]} floor {floor}")
                continue
            title = NAMES[instance]
            if len(floors) > 1:
                title = f"{title}: {titles[floor]}" if floor in titles else f"{title} {floor}"
            rows.append((title, stem, "_" if numbered else ""))
        if not rows:
            continue
        written += len(rows)
        lines.append(f"\t[{instance}] = {{ -- {NAMES[instance]}")
        for title, pattern, separator in rows:
            lua = pattern.replace("\\", "\\\\")
            lines.append(f'\t\t{{ title = "{title}", pattern = "{lua}", separator = "{separator}" }},')
        lines.append("\t},")
    lines.append(f"\t-- tiles = {TILES} per floor, drawn in four columns and three rows.")
    lines.append("}")
    pathlib = __import__("pathlib")
    pathlib.Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: {written} floors")
    for name in missing:
        print(f"missing: {name}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
