"""Generate the explicit Forever quest IDs from pinned QuestV2 CSVs (wago.tools).

Usage: python3 tools/gen_foreverquests.py [--offline | --refresh]
       python3 tools/gen_foreverquests.py FOREVER.csv ERA.csv
Sources: https://wago.tools/db2/QuestV2/csv for builds BUILD (Forever) and ERA_BUILD (Classic Era)
An unknown ID is deliberately unmarked; regenerate when the client data changes.
"""

import argparse
import csv
from pathlib import Path

from gen_classspells import db2

BUILD = "1.60.1.70205"
ERA_BUILD = "1.15.9.69722"


def ids(path):
    with Path(path).open(encoding="utf-8-sig", newline="") as source:
        return {int(row["ID"]) for row in csv.DictReader(source)}


def render(quests):
    return "\n".join(
        [
            "-- Generated by tools/gen_foreverquests.py; do not edit.",
            f"-- QuestV2: {BUILD} (Forever) minus {ERA_BUILD} (Classic Era), from wago.tools.",
            "---@type string, TFNamespace",
            "local _, ns = ...",
            "ns.ForeverQuests = {",
            *[f"\t[{quest}] = true," for quest in sorted(quests)],
            "}",
            "",
        ]
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("forever", nargs="?")
    parser.add_argument("era", nargs="?")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--offline", action="store_true")
    mode.add_argument("--refresh", action="store_true")
    args = parser.parse_args()
    if bool(args.forever) != bool(args.era):
        parser.error("provide both CSV paths, or neither to fetch the pinned builds")
    if args.forever:
        quests = ids(args.forever) - ids(args.era)
    else:
        forever, era = (
            {int(row["ID"]) for row in db2("QuestV2", build, offline=args.offline, refresh=args.refresh)}
            for build in (BUILD, ERA_BUILD)
        )
        quests = forever - era
    output = Path(__file__).resolve().parent.parent / "Data" / "ForeverQuests.lua"
    output.write_text(render(quests))


if __name__ == "__main__":
    main()
